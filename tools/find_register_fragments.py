"""Find generated functions that read a localized register before writing it.

With non_volatile_as_local / non_argument_as_local the code generator turns r14-r31 (and
r0/r2/r11/r12, f0/f14-f31, v14-v31/v32-v127) into C locals that start at zero in every
function. A real function never reads such a register before writing it (its prologue saves
them, and those saves are elided or only store into its own stack frame). A function that
does read one first is really a fragment of another function (a branch target the analysis
split off), a setjmp/longjmp-style routine, or hand-written code: it must keep the registers
in the shared context (manifest: share_registers = true).

Linear scan of each DEFINE_REX_FUNC body in text order (not control flow): a read is the
first use of a register unless the line assigns it; stores into the stack frame (ctx.r1-based
addresses, or an `ea` just computed from ctx.r1) are saves and ignored.

Usage: python -I tools/find_register_fragments.py C:/lr/generated/nvl [out.toml]
Prints a summary; writes [functions] entries with share_registers = true to out.toml.
"""
import pathlib
import re
import sys

gen = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else None

FUNC = re.compile(r"^DEFINE_REX_FUNC\((sub_([0-9A-F]{8})|[A-Za-z_][A-Za-z0-9_]*)\) \{", re.M)
DECL = re.compile(r"^\tPPC(?:V?)Register (r\d+|f\d+|v\d+)\{\};|^\tPPCRegister (f\d+)\{\};", re.M)
DECL_ANY = re.compile(r"^\tPPC\w*Register ([rfv]\d+)\{\};", re.M)
USE = re.compile(r"(?<![\w.])([rfv]\d+)\.")
ASSIGN = re.compile(r"^\t+([rfv]\d+)(?:\.[a-z0-9_\[\]]+)? = ")
STORE_INTRIN = re.compile(r"^\t+\w*store\w*\(\s*(?:\([^)]*\))?\s*&?([rfv]\d+)\.[\w\[\]]+\s*,")
# Stores to guest memory: REX_STORE_*(address, value) and simde_mm_store_*((T*)REX_RAW_ADDR(..),
# value). A register only in the value is a save (prologue spills, incl. vector saves through a
# computed address); registers in the address are real reads.
MEM_STORE = re.compile(r"^\t+(?:REX_STORE_\w+\(|\w*store\w*\(\s*\([^)]*\)\s*REX_RAW_ADDR\()")


def split_top_comma(s: str):
    depth = 0
    for i, ch in enumerate(s):
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif ch == "," and depth == 1:
            return s[:i], s[i + 1:]
    return s, ""


def scan(body: str):
    regs = set(DECL_ANY.findall(body))
    if not regs:
        return []
    seen = set()
    suspects = []
    for line in body.split("\n"):
        s = line.strip()
        if not s or s.startswith("//") or s.endswith(":") or s.startswith("PPC"):
            continue
        m = ASSIGN.match(line)
        lhs = m.group(1) if m else None
        rhs = line[m.end():] if m else line
        if not m:
            sm = STORE_INTRIN.match(line)
            if sm:
                lhs = sm.group(1)
                rhs = line[sm.end():]
            elif MEM_STORE.match(line):
                rhs, _ = split_top_comma(line[line.index("("):])  # address part only
        for r in USE.findall(rhs):
            if r in regs and r not in seen:
                suspects.append(r)
                seen.add(r)
        if lhs and lhs in regs:
            seen.add(lhs)
    return suspects


results = []
for f in sorted(gen.glob("lr_recomp.*.cpp")):
    text = f.read_text(encoding="utf-8", errors="replace")
    starts = [(m.start(), m.group(1), m.group(2)) for m in FUNC.finditer(text)]
    for i, (pos, name, addr) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        sus = scan(text[pos:end])
        if sus:
            results.append((name, addr, sus, f.name))

print(f"{len(results)} functions read a localized register before writing it")
by_reg = {}
for _, _, sus, _ in results:
    for r in sus:
        by_reg[r] = by_reg.get(r, 0) + 1
print("by register:", ", ".join(f"{r} {n}" for r, n in sorted(by_reg.items(), key=lambda x: -x[1])[:20]))
for name, addr, sus, fname in results[:40]:
    print(f"  {name} ({fname}): {' '.join(sus)}")
if out:
    lines = ["# Generated by tools/find_register_fragments.py: functions that read a localized",
             "# register before writing it (fragments / setjmp-style). Only for the register-local",
             "# codegen (lr_nvl.toml).", "[functions]"]
    for name, addr, sus, _ in results:
        if addr:
            lines.append(f"0x{addr} = {{ share_registers = true }} # {' '.join(sus)}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {sum(1 for r in results if r[1])} entries to {out}")
